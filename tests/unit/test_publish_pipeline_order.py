PIPELINES = ("scripts/live_tick.sh", "scripts/live_publish.sh")


def _invocation_lines(script: Path, name: str) -> list[int]:
    """Line numbers where `script` actually invokes `name` (not lines that merely mention it)."""
    pattern = re.compile(rf"^\s*[^#\n]*\bpython\s+scripts/{re.escape(name)}\b")
    return [n for n, line in enumerate(script.read_text().splitlines(), 1) if pattern.match(line)]


def _references(source: str, artifact: str) -> bool:
    """Does `source` name `artifact`, as a literal path or as assembled path segments?

    Exporters write either form -- `Path("data/paper/state.json")` or
    `ROOT.parent / "meridian" / "public" / "paper-state.json"` -- so checking only the literal
    would silently accept a stale declaration for any script that uses the second.
    """
    if artifact in source:
        return True
    return all(f'"{segment}"' in source for segment in artifact.split("/"))


@pytest.mark.parametrize("pipeline", PIPELINES)
def test_the_pipeline_exists_and_invokes_every_producer(pipeline: str) -> None:
    """Guards the guard: if the scan finds no invocation, every ordering case below is vacuous."""
    script = REPO / pipeline
    assert script.exists(), f"{pipeline} missing — this test cannot report a pass"
    for producer, _artifact, _consumers in EDGES:
        assert _invocation_lines(script, producer), (
            f"{pipeline} never invokes {producer}; either the pipeline changed shape or the "
            f"invocation regex no longer matches it. Both make the ordering assertion vacuous."
        )


@pytest.mark.parametrize("pipeline", PIPELINES)
def test_consumers_run_after_the_step_that_writes_their_input(pipeline: str) -> None:
    script = REPO / pipeline
    for producer, artifact, consumers in EDGES:
        produced_at = _invocation_lines(script, producer)
        assert len(produced_at) == 1, (
            f"{pipeline} invokes {producer} {len(produced_at)} times at lines {produced_at}; "
            f"with more than one write the ordering below is ambiguous, so fix the pipeline "
            f"rather than this test."
        )
        for consumer in consumers:
            for consumed_at in _invocation_lines(script, consumer):
                assert consumed_at > produced_at[0], (
                    f"{pipeline}:{consumed_at} runs {consumer} BEFORE {producer} "
                    f"(line {produced_at[0]}). {consumer} reads {artifact}, which {producer} "
                    f"writes, so it would publish the previous cycle's state."
                )


def test_every_declared_edge_is_real() -> None:
    """The list above is a claim about the code; check it against the code.

    Without this, a stale entry would keep enforcing an order for a dependency that no longer
    exists, and a mis-declared one would enforce nothing at all while looking like coverage.
    """
    for producer, artifact, consumers in EDGES:
        producer_src = (REPO / "scripts" / producer).read_text()
        assert _references(producer_src, artifact), (
            f"{producer} does not reference {artifact}, which it is declared to write"
        )
        for consumer in consumers:
            consumer_src = (REPO / "scripts" / consumer).read_text()
            assert _references(consumer_src, artifact), (
                f"{consumer} is declared a consumer of {artifact} but never references it; "
                f"remove it from EDGES or fix the path."
            )


def test_the_reference_check_can_fail() -> None:
    """A path nothing mentions must not read as referenced."""
    assert not _references("nothing to see here", "data/paper/state.json")
    assert not _references('open("data/paper/other.json")', "data/paper/state.json")
    assert _references('open("data/paper/state.json")', "data/paper/state.json")
    assert _references('ROOT / "data" / "paper" / "state.json"', "data/paper/state.json")
